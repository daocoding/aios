#!/usr/bin/env bash
# Run after editing apps/content-review/static/*: copies the shared UI into public/ and regenerates lib/spec.js
# (the server-side copy of tools.json used to compute formulas on GET).
# The review queue is served at / and at /review (review.html), so a landing page can take / (prepare-deploy.sh --with-site).
set -e; cd "$(dirname "$0")"
cp ../apps/content-review/static/{index.html,tools.html,tools.json,sheets.js,signup.js} public/
cp public/index.html public/review.html
node -e 'const fs=require("fs");const d=fs.readFileSync("public/tools.json","utf8");JSON.parse(d);fs.writeFileSync("lib/spec.js","// Generated by sync.sh from apps/content-review/static/tools.json. Do not edit.\nexport default "+d.trim()+";\n")'
echo synced
